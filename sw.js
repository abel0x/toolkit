/* ─── Install ────────────────────────────────────────────────── */
self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      // Bypass the HTTP cache: GitHub Pages lets browsers keep files for ten
      // minutes, which could put the previous release into a new cache.
      .then((cache) => cache.addAll(PRECACHE_ASSETS.map((asset) => new Request(asset, { cache: 'reload' }))))
      .then(() => self.skipWaiting())
  );
});

/* ─── Activate ───────────────────────────────────────────────── */
self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => key.startsWith('toolkit-') && key !== CACHE_NAME)
            .map((key) => caches.delete(key))
        )
      )
      .then(() => self.clients.claim())
  );
});

/* ─── Fetch ──────────────────────────────────────────────────── */
self.addEventListener('fetch', (event) => {
  const { request } = event;

  /* Only handle GET requests */
  if (request.method !== 'GET') return;

  const url = new URL(request.url);

  /* Skip non-http(s) schemes (chrome-extension etc.) */
  if (!url.protocol.startsWith('http')) return;

  /* Only handle same-origin requests (fonts are now local) */
  if (url.origin !== self.location.origin) return;

  const isHTML = request.headers.get('accept')?.includes('text/html');

  /* ── HTML → Network-first ── */
  if (isHTML) {
    event.respondWith(networkFirst(request));
    return;
  }

  /* ── Versioned CSS/JS from a newer release → network, cache as fallback ── */
  const version = url.searchParams.get('v');
  if (version !== null) {
    url.searchParams.delete('v');
    event.respondWith(version === CACHE_VERSION ? cacheFirst(request, url.href) : networkFirst(request, url.href));
    return;
  }

  /* ── All other same-origin assets → Cache-first ── */
  event.respondWith(cacheFirst(request));
});

/* ─── Strategies ─────────────────────────────────────────────── */

/**
 * Network-first: try the network, cache the response, fall back to cache.
 * Falls back to 404.html when completely offline and no cache exists.
 */
async function networkFirst(request, key = request) {
  try {
    const response = await fetch(request);
    // A newer release's asset must not replace this release's copy.
    if (response.ok && key === request) {
      const cache = await caches.open(CACHE_NAME);
      cache.put(request, response.clone());
    }
    return response;
  } catch {
    const cached = await caches.match(key);
    if (cached) return cached;
    if (key !== request) return new Response('', { status: 503, statusText: 'Service Unavailable' });
    /* /tr/ pages are cached on visit. Offline, redirect an unvisited one to
       its precached English twin; language-redirect.js's loop guard keeps it
       there, in English, instead of sending it back. */
    const scope = new URL(self.registration.scope);
    const url = new URL(request.url);
    if (request.mode === 'navigate' && url.pathname.startsWith(`${scope.pathname}tr/`)) {
      const english = new URL(url.pathname.slice(scope.pathname.length + 3), scope);
      for (const candidate of english.pathname.endsWith('/') ? [english.href, `${english.href}index.html`] : [english.href]) {
        if (await caches.match(candidate, { ignoreSearch: true })) return Response.redirect(candidate, 302);
      }
    }
    return caches.match('404.html');
  }
}

/**
 * Cache-first: serve from cache if available, otherwise fetch, cache,
 * and return. Silently ignores non-OK responses (e.g. 404).
 */
async function cacheFirst(request, key = request) {
  const cached = await caches.match(key);
  if (cached) return cached;

  try {
    const response = await fetch(request);
    if (response.ok) {
      const cache = await caches.open(CACHE_NAME);
      cache.put(key, response.clone());
    }
    return response;
  } catch {
    return new Response('', { status: 503, statusText: 'Service Unavailable' });
  }
}
